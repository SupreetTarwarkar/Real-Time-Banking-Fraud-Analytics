EXPECTED_COLUMNS = [
    "location_id",
    "city",
    "state_ut",
    "region",
    "latitude",
    "longitude",
]


def build_dim_location():
    """Create and validate the finalized DimLocation dataframe."""
    df = pd.DataFrame(LOCATIONS, columns=EXPECTED_COLUMNS)

    # Final validation checks
    assert len(df) == 105, f"Expected 105 locations, found {len(df)}"
    assert df["location_id"].is_unique, "location_id must be unique"
    assert not df.duplicated(["city", "state_ut"]).any(), "Duplicate city/state rows found"
    assert df["state_ut"].nunique() == 36, "All 28 states + 8 UTs must be represented"
    assert df["latitude"].between(-90, 90).all(), "Invalid latitude found"
    assert df["longitude"].between(-180, 180).all(), "Invalid longitude found"
    assert df.notna().all().all(), "Null values found in DimLocation"

    return df


def choose_save_folder():
    """Ask the user where the generated DimLocation CSV should be saved."""
    root = tk.Tk()
    root.withdraw()
    root.attributes("-topmost", True)
    folder = filedialog.askdirectory(title="Select folder to save DimLocation CSV")
    root.destroy()
    return Path(folder) if folder else None


def main():
    df = build_dim_location()

    output_dir = choose_save_folder()
    if output_dir is None:
        print("No folder selected. Nothing was saved.")
        return

    # Date format: YYYYMMDD, e.g. DimLocation_20261003.csv
    date_stamp = datetime.now().strftime("%Y%m%d")
    csv_path = output_dir / f"DimLocation_{date_stamp}.csv"

    # FINAL OUTPUT RULE: create one CSV only.
    df.to_csv(csv_path, index=False, encoding="utf-8-sig")

    print("\nDimLocation generated successfully.")
    print(f"Rows             : {len(df):,}")
    print(f"States / UTs     : {df['state_ut'].nunique()}")
    print(f"Location ID range: {df['location_id'].min()} - {df['location_id'].max()}")
    print(f"Output CSV       : {csv_path.resolve()}")

    root = tk.Tk()
    root.withdraw()
    root.attributes("-topmost", True)
    messagebox.showinfo(
        "DimLocation Complete",
        f"File saved successfully:\n\n{csv_path.name}",
    )
    root.destroy()


if __name__ == "__main__":
    main()